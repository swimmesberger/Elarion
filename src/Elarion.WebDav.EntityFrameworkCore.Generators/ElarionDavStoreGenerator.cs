using System.Collections.Immutable;
using System.Text;
using Elarion.Generators;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Elarion.WebDav.EntityFrameworkCore.Generators;

/// <summary>
/// Fills every partial <c>DbContext</c> annotated with <c>[GenerateElarionDavStore]</c> with the
/// <c>ElarionDavCollections</c>, <c>ElarionDavObjects</c> and <c>ElarionDavChanges</c> sets and an implementation of
/// the EF generator's per-feature model-configuration seam that calls <c>UseElarionDavStore</c>, as
/// <c>[GenerateElarionAppPasswords]</c> does.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class ElarionDavStoreGenerator : IIncrementalGenerator {
    private const string AttributeMetadataName = "Elarion.WebDav.EntityFrameworkCore.GenerateElarionDavStoreAttribute";
    private const string GenerateDbSetsAttributeName = ElarionGeneratorConventions.GenerateDbSetsAttribute;
    private const string StoreNamespace = "global::Elarion.WebDav.EntityFrameworkCore";

    // The per-feature seam DbContextGenerator declares for this attribute: both sides derive the name from the same
    // convention, so they cannot drift.
    private static readonly string SeamMethodName = ElarionGeneratorConventions.ModelConfigurationSeamName("GenerateElarionDavStoreAttribute");

    private static readonly DiagnosticDescriptor MissingGenerateDbSets = new(
        "ELDAV001",
        "[GenerateElarionDavStore] requires [GenerateDbSets]",
        "Context '{0}' is annotated with [GenerateElarionDavStore] but not [GenerateDbSets]; add [GenerateDbSets] "
        + "so the DAV store's DbSets and model-configuration seam are generated",
        "Elarion.WebDav.EntityFrameworkCore",
        DiagnosticSeverity.Error,
        true);

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context) {
        var targets = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                AttributeMetadataName,
                static (node, _) => node is ClassDeclarationSyntax,
                static (ctx, _) => GetTarget(ctx))
            .Where(static target => target is not null)
            .WithTrackingName("DavStoreTargets");

        context.RegisterSourceOutput(targets, static (spc, target) => {
            if (target is null) return;
            foreach (var diagnostic in target.Diagnostics) spc.ReportDiagnostic(diagnostic.ToDiagnostic());
            if (target.Emit) Emit(spc, target);
        });
    }

    private sealed record DavStoreTarget(
        string Namespace,
        string ContextName,
        string HintName,
        bool SnakeCase,
        string? Schema,
        bool Emit,
        EquatableArray<DiagnosticInfo> Diagnostics);

    private static DavStoreTarget? GetTarget(GeneratorAttributeSyntaxContext ctx) {
        if (ctx.TargetSymbol is not INamedTypeSymbol contextSymbol) return null;

        var snakeCase = true;
        string? schema = null;
        if (ctx.Attributes.Length > 0)
            foreach (var namedArgument in ctx.Attributes[0].NamedArguments)
                switch (namedArgument.Key) {
                    case "SnakeCase" when namedArgument.Value.Value is bool value:
                        snakeCase = value;
                        break;
                    case "Schema" when namedArgument.Value.Value is string schemaValue:
                        schema = schemaValue;
                        break;
                }

        var ns = contextSymbol.ContainingNamespace is { IsGlobalNamespace: false } containing ? containing.ToDisplayString() : "";
        var contextName = contextSymbol.Name;
        var hintName = (ns.Length == 0 ? contextName : ns + "." + contextName).Replace('.', '_');
        var hasGenerateDbSets = contextSymbol.GetAttributes()
            .Any(attribute => attribute.AttributeClass?.ToDisplayString() == GenerateDbSetsAttributeName);

        var diagnostics = ImmutableArray.CreateBuilder<DiagnosticInfo>();
        if (!hasGenerateDbSets)
            diagnostics.Add(DiagnosticInfo.Create(MissingGenerateDbSets, LocationInfo.From(contextSymbol),
                contextSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)));

        return new DavStoreTarget(ns, contextName, hintName, snakeCase, schema, hasGenerateDbSets, diagnostics.ToImmutable());
    }

    private static void Emit(SourceProductionContext spc, DavStoreTarget target) {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// Source: Elarion.WebDav.EntityFrameworkCore.Generators.ElarionDavStoreGenerator");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable CS1591 // Generated code is not documented; a consuming project that enables GenerateDocumentationFile must not be warned about it.");
        sb.AppendLine();
        sb.AppendLine("using Microsoft.EntityFrameworkCore;");
        sb.AppendLine();
        if (target.Namespace.Length > 0) {
            sb.AppendLine($"namespace {target.Namespace};");
            sb.AppendLine();
        }

        sb.AppendLine($"partial class {target.ContextName}");
        sb.AppendLine("{");
        sb.AppendLine($"    public DbSet<{StoreNamespace}.DavCollectionEntity> ElarionDavCollections => Set<{StoreNamespace}.DavCollectionEntity>();");
        sb.AppendLine($"    public DbSet<{StoreNamespace}.DavObjectEntity> ElarionDavObjects => Set<{StoreNamespace}.DavObjectEntity>();");
        sb.AppendLine($"    public DbSet<{StoreNamespace}.DavChangeEntity> ElarionDavChanges => Set<{StoreNamespace}.DavChangeEntity>();");
        sb.AppendLine();
        sb.AppendLine("    // Implements the per-feature model-configuration seam the EF DbContext generator calls at the");
        sb.AppendLine("    // end of ConfigureEntities, so it composes with the other [GenerateElarion*] features.");
        sb.AppendLine($"    partial void {SeamMethodName}(ModelBuilder modelBuilder) =>");
        sb.AppendLine($"        {StoreNamespace}.DavStoreModelBuilderExtensions.UseElarionDavStore(");
        sb.AppendLine($"            modelBuilder, schema: {SourceLiterals.String(target.Schema)}, snakeCase: {(target.SnakeCase ? "true" : "false")});");
        sb.AppendLine("}");

        spc.AddSource($"{target.HintName}.ElarionDavStore.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }
}
