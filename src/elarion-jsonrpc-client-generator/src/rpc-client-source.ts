// The uploader inside createRpcClient: the configured one, or a raw POST to the direct-upload endpoint with the
// client's own fetch and headers (the endpoint reads a raw body without buffering it as a form).
function generateUploaderLines(): string[] {
  return [
    '  const uploadUrl = options.uploadUrl ?? defaultUploadUrl(options.url)',
    '  const upload: RpcFileUploader = options.uploadFile ?? postUpload',
    '',
    '  // The default uploader: the raw body to the direct-upload endpoint (MapElarionBlobUploads), which answers',
    '  // the blob id as text/plain. Headers come from the client options; a headers function sees no methods.',
    '  async function postUpload(file: Blob, uploadOptions: RpcUploadOptions): Promise<UploadedFileRef> {',
    '    const headers = await buildHeaders(options.headers, { methods: [], batch: false }, undefined, undefined)',
    "    headers.set('Content-Type', file.type || 'application/octet-stream')",
    "    const fileName = uploadOptions.fileName ?? (file instanceof File ? file.name : '')",
    '    let target = uploadUrl',
    "    if (fileName !== '') {",
    '      // A header carries Latin-1 only, so a name outside printable ASCII travels percent-encoded in the query.',
    '      if (/^[\\x20-\\x7e]*$/.test(fileName)) {',
    "        headers.set('X-Elarion-File-Name', fileName)",
    '      } else {',
    "        target = withQueryParameter(uploadUrl, 'fileName', fileName)",
    '      }',
    '    }',
    '',
    "    const response = await fetchImpl(target, { method: 'POST', headers, body: file, signal: uploadOptions.signal })",
    '    if (!response.ok) {',
    '      throw new RpcTransportError(response.status, response.statusText, await response.text())',
    '    }',
    '',
    '    const reference = (await response.text()).trim()',
    "    if (reference === '') {",
    "      throw new RpcProtocolError('The upload endpoint answered without a file reference.')",
    '    }',
    '    return reference',
    '  }',
    '',
    "  // The uploader of one call's staging: the call's AbortSignal cancels its uploads too.",
    '  function uploaderFor(signal: AbortSignal | undefined): (file: Blob) => Promise<UploadedFileRef> {',
    '    return (file) => upload(file, { signal })',
    '  }',
    '',
  ]
}

// The params of one batch item on the wire: uploads staged first, then files encoded, each only when the schema
// has them, so a schema with files alone keeps its expression.
function batchParamsExpression(hasFiles: boolean, hasUploads: boolean): string {
  const staged = hasUploads
    ? 'await stageUploadParams(item.method, item.params, uploaderFor(requestOptions?.signal))'
    : 'item.params'
  return hasFiles ? `await encodeFileParams(item.method, ${staged})` : staged
}

// The runtime upload staging, emitted only for schemas whose params take uploaded files: after params validation,
// every File/Blob at an upload position is uploaded and replaced by its reference, while a reference uploaded
// earlier (a string) is sent as it is. Every API used is standard in browsers and Node 20+ (Blob, File, URL, fetch).
function generateUploadStagingLines(): string[] {
  return [
    'async function stageUploadParams(',
    '  method: RpcMethod,',
    '  params: unknown,',
    '  upload: (file: Blob) => Promise<UploadedFileRef>',
    '): Promise<unknown> {',
    '  const paths = rpcParamsUploadPaths[method]',
    '  if (!paths) return params',
    '  let value = params',
    '  for (const path of paths) {',
    '    value = await stageUploadsAtPath(value, path, 0, upload)',
    '  }',
    '  return value',
    '}',
    '',
    'async function stageUploadsAtPath(',
    '  value: unknown,',
    '  path: readonly string[],',
    '  index: number,',
    '  upload: (file: Blob) => Promise<UploadedFileRef>',
    '): Promise<unknown> {',
    '  if (index === path.length) {',
    '    return value instanceof Blob ? upload(value) : value',
    '  }',
    '',
    '  const segment = path[index]',
    "  if (segment === '*') {",
    '    if (!Array.isArray(value)) return value',
    '    return Promise.all(value.map((item) => stageUploadsAtPath(item, path, index + 1, upload)))',
    '  }',
    '',
    '  if (!isRecord(value) || value[segment] === undefined) return value',
    '  return { ...value, [segment]: await stageUploadsAtPath(value[segment], path, index + 1, upload) }',
    '}',
    '',
    '// The direct-upload endpoint on the origin of the RPC url, whose route is not under the RPC path. A relative',
    "// RPC url ('/rpc') keeps the endpoint relative to the page.",
    'function defaultUploadUrl(url: string | URL): string | URL {',
    '  try {',
    "    return new URL('/_elarion/blobs', url)",
    '  } catch {',
    "    return '/_elarion/blobs'",
    '  }',
    '}',
    '',
    'function withQueryParameter(url: string | URL, name: string, value: string): string | URL {',
    '  if (url instanceof URL) {',
    '    const copy = new URL(url)',
    '    copy.searchParams.set(name, value)',
    '    return copy',
    '  }',
    "  return `${url}${url.includes('?') ? '&' : '?'}${encodeURIComponent(name)}=${encodeURIComponent(value)}`",
    '}',
    '',
  ]
}
